const HIGH_WORD_ABS_MASK = 0x7fffffff;
const HIGH_WORD_EXPONENT_MASK = 0x7ff00000;
import { getHighWord } from './bits.ts';
import { kernelCos } from './kernel-cos.ts';
import { kernelSin } from './kernel-sin.ts';
import { rempio2 } from './range-reduction.ts';

// High word for PI/4: 0x3fe921fb = 1072243195 => 00111111111010010010000111111011
let PIO4_HIGH_WORD = 1072243195; // asm type annotation

// 2^-26 = 1.4901161193847656e-8 => 0011111001010000000000000000000000000000000000000000000000000000 => high word => 00111110010100000000000000000000 => 0x3e500000 = 1045430272
let SMALL_HIGH_WORD = 1045430272; // asm type annotation

// Array for storing remainder elements:
let Y = [ 0.0, 0.0 ];

export function sin(x: number): number {
	let ix;
	let n;

	ix = getHighWord( x );
	ix &= HIGH_WORD_ABS_MASK;

	// Case: |x| ~< π/4
	if ( ix <= PIO4_HIGH_WORD ) {
		// Case: |x| ~< 2^-26
		if ( ix < SMALL_HIGH_WORD ) {
			return x;
		}
		return kernelSin( x, 0.0 );
	}
	// Case: x is NaN or infinity
	if ( ix >= HIGH_WORD_EXPONENT_MASK ) {
		return NaN;
	}
	// Argument reduction...
	n = rempio2( x, Y );
	switch ( n & 3 ) {
	case 0:
		return kernelSin( Y[ 0 ], Y[ 1 ] );
	case 1:
		return kernelCos( Y[ 0 ], Y[ 1 ] );
	case 2:
		return -kernelSin( Y[ 0 ], Y[ 1 ] );
	default:
		return -kernelCos( Y[ 0 ], Y[ 1 ] );
	}
}

