import path from "node:path";
import {
  FACTORY_MODULE_API_VERSION,
  FACTORY_MODULE_VERSION,
  factoryModuleCatalog,
} from "@hyperfocus/pad-pilot/factory-modules";

const factoryCapabilityCapacity = Math.max(
  1,
  ...factoryModuleCatalog.map((module) => module.capabilities.length),
);
export const FACTORY_MODULE_HEADER_PATH = path.join(
  import.meta.dir,
  "..",
  "plugin",
  "generated",
  "factory-module-catalog.h",
);

function cppString(value: string) {
  return JSON.stringify(value);
}

export function renderFactoryModuleHeader() {
  const definitions = factoryModuleCatalog.map((module) => {
    const capabilities = [
      ...module.capabilities.map(cppString),
      ...Array.from({ length: factoryCapabilityCapacity - module.capabilities.length }, () => "{}"),
    ].join(", ");
    return `    Definition {${cppString(module.id)}, ${cppString(module.name)}, ${cppString(module.uiEntry)}, {${capabilities}}, ${module.capabilities.length}},`;
  });

  return `// Generated by scripts/generate-factory-modules.ts. Do not edit.
#pragma once

#include <array>
#include <cstddef>
#include <string_view>

namespace padpilot::factory_catalog {

inline constexpr std::string_view kFactoryVersion = ${cppString(FACTORY_MODULE_VERSION)};
inline constexpr std::string_view kModuleApiVersion = ${cppString(FACTORY_MODULE_API_VERSION)};

struct Definition {
  std::string_view id;
  std::string_view name;
  std::string_view uiEntry;
  std::array<std::string_view, ${factoryCapabilityCapacity}> capabilities;
  std::size_t capabilityCount;
};

inline constexpr std::array<Definition, ${factoryModuleCatalog.length}> kModules {{
${definitions.join("\n")}
}};

}  // namespace padpilot::factory_catalog
`;
}

export async function generateFactoryModuleHeader() {
  await Bun.write(FACTORY_MODULE_HEADER_PATH, renderFactoryModuleHeader());
}

if (import.meta.main) {
  await generateFactoryModuleHeader();
}
