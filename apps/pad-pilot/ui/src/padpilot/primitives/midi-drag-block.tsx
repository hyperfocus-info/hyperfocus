import { safeFilename } from "./utils/midi-drag-block-values";
import * as stylex from "@stylexjs/stylex";
import { For, createMemo, createSignal, onCleanup } from "solid-js";
import { Download, FileDown, GripHorizontal } from "lucide-solid";
import { hasNativeHostTransport } from "../../bridge";
import { Button } from "../../components/elements/button";
import { IO } from "../provider";
import { midi } from "../midi";
import { PADPILOT_FILE_IMPORT_MAX_BYTES } from "@hyperfocus/pad-pilot/file-import";
import { primitiveStyles as styles } from "./primitives.stylex";

export interface MidiDragBlockProps {
  /** Standard MIDI file bytes to drag or import. */
  midiData: Uint8Array;
  /** Target filename for drag/import operations. */
  filename: string;
  /** Visible block label. */
  label: string;
  /** Disables interactions when no generated bytes exist. */
  disabled?: boolean;
  classNames?: {
    downloadButton?: string;
    root?: string;
    titleStrong?: string;
  };
}



function createMidiFile(bytes: Uint8Array, filename: string) {
  return new File([bytes.slice()], safeFilename(filename), { type: "audio/midi" });
}

/** MidiDragBlock exposes a compact generated-MIDI drag target backed by PadPilot public APIs. */
export function MidiDragBlock(props: MidiDragBlockProps) {
  const [status, setStatus] = createSignal("Ready");
  const [transferring, setTransferring] = createSignal(false);
  const byteCount = createMemo(() => props.midiData.length);
  const disabled = createMemo(() => props.disabled || byteCount() === 0 || byteCount() > PADPILOT_FILE_IMPORT_MAX_BYTES);
  const interactionDisabled = createMemo(() => disabled() || transferring());
  const hotMarkerCount = createMemo(() => Math.max(1, Math.min(16, Math.ceil(byteCount() / 96))));
  const urlReleaseTimers = new Map<string, number>();
  let disposed = false;
  let transferGeneration = 0;

  const releaseUrl = (url: string) => {
    const timeoutId = urlReleaseTimers.get(url);
    if (timeoutId !== undefined) {
      window.clearTimeout(timeoutId);
      urlReleaseTimers.delete(url);
    }
    URL.revokeObjectURL(url);
  };

  const scheduleUrlRelease = (url: string) => {
    if (urlReleaseTimers.size >= 8) {
      const oldestUrl = urlReleaseTimers.keys().next().value;
      if (typeof oldestUrl === "string") {
        releaseUrl(oldestUrl);
      }
    }
    urlReleaseTimers.set(url, window.setTimeout(() => releaseUrl(url), 5000));
  };

  const downloadMidiData = () => {
    const file = createMidiFile(props.midiData, props.filename);
    const url = URL.createObjectURL(file);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = file.name;
    document.body.append(anchor);
    anchor.click();
    anchor.remove();
    scheduleUrlRelease(url);
  };

  onCleanup(() => {
    disposed = true;
    transferGeneration += 1;
    for (const url of [...urlReleaseTimers.keys()]) {
      releaseUrl(url);
    }
  });
  const indicators = createMemo(() => [
    byteCount() > 0,
    status() !== "Ready",
    !disabled(),
  ]);

  const requestTransfer = async () => {
    if (interactionDisabled()) {
      return;
    }

    const requestId = ++transferGeneration;
    setTransferring(true);
    try {
      if (hasNativeHostTransport()) {
        setStatus(midi.beginDrag(props.midiData, props.filename) ? "Native drag started" : "Native drag unavailable");
        return;
      }

      await IO.importFile(createMidiFile(props.midiData, props.filename), {
        category: "midi",
        maxBytes: PADPILOT_FILE_IMPORT_MAX_BYTES,
      });
      if (!disposed && requestId === transferGeneration) {
        setStatus("Prepared for import");
      }
    } catch {
      if (!disposed && requestId === transferGeneration) {
        setStatus("Import failed");
      }
    } finally {
      if (!disposed && requestId === transferGeneration) {
        setTransferring(false);
      }
    }
  };

  const handleDragStart = (event: DragEvent) => {
    if (interactionDisabled()) {
      event.preventDefault();
      return;
    }

    const file = createMidiFile(props.midiData, props.filename);
    const url = URL.createObjectURL(file);
    scheduleUrlRelease(url);
    event.dataTransfer?.setData("DownloadURL", `audio/midi:${file.name}:${url}`);
    event.dataTransfer?.setData("application/x-padpilot-midi", file.name);
    event.dataTransfer?.setData("text/plain", file.name);
    if (event.dataTransfer) {
      event.dataTransfer.effectAllowed = "copy";
    }
    midi.beginDrag(props.midiData, file.name);
    setStatus("Dragging MIDI");
  };

  return (
    <div
      class={`${stylex.attrs(styles.midiDragBlock, interactionDisabled() && styles.midiDragDisabled).class} ${props.classNames?.root ?? ""}`.trim()}
      data-disabled={interactionDisabled() ? "true" : "false"}
      draggable={!interactionDisabled()}
      role="button"
      tabIndex={interactionDisabled() ? -1 : 0}
      aria-disabled={interactionDisabled() ? "true" : "false"}
      onClick={() => {
        requestTransfer();
      }}
      onDragStart={handleDragStart}
      onDragEnd={() => setStatus("Ready")}
      onKeyDown={(event) => {
        if (event.key !== "Enter" && event.key !== " ") {
          return;
        }
        event.preventDefault();
        requestTransfer();
      }}
    >
      <span {...stylex.attrs(styles.topline)}>
        <span {...stylex.attrs(styles.title)}>
          <strong class={`${stylex.attrs(styles.titleStrong).class} ${props.classNames?.titleStrong ?? ""}`.trim()}>{props.label}</strong>
          <small {...stylex.attrs(styles.titleSmall)}>{safeFilename(props.filename)}</small>
        </span>
        <span {...stylex.attrs(styles.actions)}>
          <GripHorizontal size={18} aria-hidden="true" />
          <Button
            class={`${stylex.props(styles.downloadButton).className ?? ""} ${props.classNames?.downloadButton ?? ""}`.trim()}
            disabled={interactionDisabled()}
            icon={Download}
            onClick={(event) => {
              event.stopPropagation();
              downloadMidiData();
              setStatus("Downloaded");
            }}
            size="sm"
            tooltip={`Download ${props.label}`}
            variant="ghost"
          />
        </span>
      </span>
      <span {...stylex.attrs(styles.markers)} aria-hidden="true">
        <For each={Array.from({ length: 16 }, (_, index) => index + 1)}>
          {(index) => (
            <span {...stylex.attrs(styles.marker, index <= hotMarkerCount() && styles.markerHot)} data-hot={index <= hotMarkerCount() ? "true" : "false"}>
              {index}
            </span>
          )}
        </For>
      </span>
      <span {...stylex.attrs(styles.footer)}>
        <span>{status()}</span>
        <span {...stylex.attrs(styles.indicators)} aria-hidden="true">
          <For each={indicators()}>
            {(active) => <span {...stylex.attrs(styles.light, active && styles.lightActive)} data-active={active ? "true" : "false"} />}
          </For>
        </span>
        <FileDown size={14} aria-hidden="true" />
      </span>
    </div>
  );
}
